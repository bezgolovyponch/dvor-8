// The same shape under another name: the Russian letters that are Latin ones, and marks drawn alike.
const LETTER = { А: 'A', В: 'B', Е: 'E', Ё: 'E', К: 'K', М: 'M', Н: 'H', О: 'O', Р: 'P', С: 'C', Т: 'T', Х: 'X' };
const MARK = { '—': '-', '–': '-', '−': '-', '“': '"', '”': '"', '„': '"', '’': "'", '‘': "'", '№': 'N', '•': '·' };

// Each letter as seven numbers, one a row, the left dot the high bit.
const GLYPHS = Object.fromEntries(Object.entries(DOTS).map(([ch, dots]) => [ch, dots.split(' ').map((row) => parseInt(row, 2))]));
const has = (ch) => Boolean(GLYPHS[ch] || LETTER[ch]);

// Text as this font can write it: capitals, marks folded to the ones it has, an accent dropped from a
// Latin letter (Kensō → KENSO), and a space in place of anything it has no dots for.
export function plain(text) {
  let out = '';
  for (const raw of String(text).replace(/…/g, '...').toUpperCase()) {
    const ch = MARK[raw] || raw, base = ch.normalize('NFD')[0];
    out += has(ch) ? ch : has(base) ? base : ' ';
  }
  return out.replace(/ {2,}/g, ' ').trim();
}

export const glyph = (ch) => GLYPHS[ch] || GLYPHS[LETTER[ch]] || GLYPHS[' '];
export const textWidth = (text) => Math.max(0, text.length * ADVANCE - 1);
